// Extracts the bit patterns of every predefined ArUco / AprilTag dictionary from the
// bundled OpenCV.js build and writes them to src/targets/dictionaries.data.js (an ES module).
//
// Targets are rendered from this table (vector PDF/SVG/PNG) so the Targets page works
// instantly, without waiting for the 5 MB WebAssembly engine to download.
//
// Usage: node scripts/extract-dictionaries.cjs
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'src', 'targets', 'dictionaries.data.js');

// Each family stores the bits of its largest variant; the smaller variants are prefixes.
const FAMILIES = [
  { family: '4X4', base: 'DICT_4X4_1000', variants: ['DICT_4X4_50', 'DICT_4X4_100', 'DICT_4X4_250', 'DICT_4X4_1000'] },
  { family: '5X5', base: 'DICT_5X5_1000', variants: ['DICT_5X5_50', 'DICT_5X5_100', 'DICT_5X5_250', 'DICT_5X5_1000'] },
  { family: '6X6', base: 'DICT_6X6_1000', variants: ['DICT_6X6_50', 'DICT_6X6_100', 'DICT_6X6_250', 'DICT_6X6_1000'] },
  { family: '7X7', base: 'DICT_7X7_1000', variants: ['DICT_7X7_50', 'DICT_7X7_100', 'DICT_7X7_250', 'DICT_7X7_1000'] },
  { family: 'ARUCO_ORIGINAL', base: 'DICT_ARUCO_ORIGINAL', variants: ['DICT_ARUCO_ORIGINAL'] },
  { family: 'APRILTAG_16h5', base: 'DICT_APRILTAG_16h5', variants: ['DICT_APRILTAG_16h5'] },
  { family: 'APRILTAG_25h9', base: 'DICT_APRILTAG_25h9', variants: ['DICT_APRILTAG_25h9'] },
  { family: 'APRILTAG_36h10', base: 'DICT_APRILTAG_36h10', variants: ['DICT_APRILTAG_36h10'] },
  { family: 'APRILTAG_36h11', base: 'DICT_APRILTAG_36h11', variants: ['DICT_APRILTAG_36h11'] },
  { family: 'ARUCO_MIP_36h12', base: 'DICT_ARUCO_MIP_36h12', variants: ['DICT_ARUCO_MIP_36h12'] },
];

function markerBits(cv, dict, id) {
  const n = dict.markerSize;
  const img = new cv.Mat();
  cv.generateImageMarker(dict, id, n + 2, img, 1); // exactly one pixel per bit
  const bits = new Uint8Array(n * n);
  for (let y = 0; y < n; y++) for (let x = 0; x < n; x++) bits[y * n + x] = img.ucharAt(y + 1, x + 1) > 127 ? 1 : 0;
  img.delete();
  return bits;
}

function pack(allBits) {
  const bytes = new Uint8Array(Math.ceil(allBits.length / 8));
  allBits.forEach((b, i) => { if (b) bytes[i >> 3] |= 0x80 >> (i & 7); });
  return Buffer.from(bytes).toString('base64');
}

(async () => {
  const cv = await require('./load-opencv.cjs')();
  const out = { generatedFrom: 'OpenCV ' + cv.getBuildInformation().match(/OpenCV (\S+)/)[1], families: {}, dictionaries: {} };

  for (const f of FAMILIES) {
    const base = cv.getPredefinedDictionary(cv[f.base]);
    const n = base.markerSize, count = base.bytesList.rows;
    const all = [];
    const perId = [];
    for (let id = 0; id < count; id++) { const b = markerBits(cv, base, id); perId.push(b); all.push(...b); }
    out.families[f.family] = { markerSize: n, count, bits: pack(all) };

    for (const v of f.variants) {
      const d = cv.getPredefinedDictionary(cv[v]);
      const vc = d.bytesList.rows;
      // Verify the prefix property this table relies on.
      for (let id = 0; id < vc; id++) {
        const b = markerBits(cv, d, id);
        if (b.some((bit, i) => bit !== perId[id][i])) throw new Error(`${v} id ${id} is not a prefix of ${f.base}`);
      }
      out.dictionaries[v] = { family: f.family, markerSize: n, count: vc, maxCorrectionBits: d.maxCorrectionBits, cvEnum: cv[v] };
      d.delete();
    }
    base.delete();
    console.log(`${f.family}: ${count} markers of ${n}x${n} bits (${f.variants.join(', ')})`);
  }

  fs.writeFileSync(OUT, `// Generated by scripts/extract-dictionaries.cjs — do not edit.\nexport default ${JSON.stringify(out)};\n`);
  console.log('wrote', path.relative(ROOT, OUT), (fs.statSync(OUT).size / 1024).toFixed(1) + ' KB');
})().catch((e) => { console.error(e); process.exit(1); });
